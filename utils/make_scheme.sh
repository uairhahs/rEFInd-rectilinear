#!/bin/bash
# Derive the theme colours (from the wallpaper or given seed colours) with matugen (Material Color
# Utilities) and write them to scheme.sh, which tokens.sh reads. Re-run (via
# build.sh) whenever background.png changes.
# usage: make_scheme.sh [WALLPAPER]   (default: ../rectilinear/background.png)
set -euo pipefail
HERE=$(dirname "$0")
# shellcheck source=tokens.sh
source "$HERE/tokens.sh"
WALL=${1:-"$HERE/../rectilinear/background.png"}

scheme() { # SEED: "#rrggbb" or a wallpaper colour index
  case $1 in
    \#*) matugen color hex "$1" --dry-run -j hex -m dark -t "$M3_SCHEME" ;;
    *)   matugen image "$WALL" --dry-run -j hex -m dark --source-color-index "$1" -t "$M3_SCHEME" ;;
  esac
}
col() { jq -r ".colors.$2 | .dark.color // .dark // ." <<<"$1"; }
p=$(scheme "$M3_PRIMARY_SEED")
s=$(scheme "$M3_SECONDARY_SEED")
cat > "$HERE/scheme.sh" <<SH
# Generated by make_scheme.sh from $(basename "$WALL") ($M3_SCHEME, dark). Do not edit.
M3_PRIMARY_SOURCE='$(col "$p" source_color)'
M3_SECONDARY_SOURCE='$(col "$s" source_color)'
M3_PRIMARY='$(col "$p" primary_container)'
M3_ON_PRIMARY='$(col "$p" on_primary_container)'
M3_SECONDARY='$(col "$s" primary_container)'
M3_ON_SECONDARY='$(col "$s" on_primary_container)'
M3_SURFACE='$(col "$p" surface)'
M3_ON_SURFACE='$(col "$p" on_surface)'
SH
cat "$HERE/scheme.sh"
